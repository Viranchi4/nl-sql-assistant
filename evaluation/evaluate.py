import json
import argparse
from decimal import Decimal
from pathlib import Path

from nl_sql_assistant.pipeline import run_text_to_sql
from nl_sql_assistant.sql.executor import execute_query
from nl_sql_assistant.llm.ollama_client import DEFAULT_MODEL

def load_questions(dataset: str):
    questions_path = Path(__file__).parent / dataset

    with open(questions_path, "r", encoding="utf-8") as file:
        return json.load(file)

def normalize_value(value):
    """
    Normalize database values before comparison.

    Decimal values are normalized so equivalent numeric
    results compare consistently.
    """
    if isinstance(value, Decimal):
        return value.normalize()

    return value


def normalize_rows(rows):
    """
    Convert dictionary rows into comparable tuples.

    Column aliases generated by the LLM may differ from the
    reference SQL, so comparison is based on returned values
    rather than dictionary key names.
    """
    normalized = []

    for row in rows:
        normalized_row = tuple(
            normalize_value(value)
            for value in row.values()
        )

        normalized.append(normalized_row)

    # For this first evaluator version, compare result sets
    # without depending on database row-return order.
    return sorted(normalized, key=repr)


def results_match(generated_results, reference_results):
    return normalize_rows(generated_results) == normalize_rows(reference_results)


def main():
    parser = argparse.ArgumentParser(
        description="Evaluate the NL-to-SQL pipeline."
    )

    parser.add_argument(
        "--dataset",
        default="questions.json",
        help="Evaluation dataset filename inside the evaluation folder.",
    )

    args = parser.parse_args()

    questions = load_questions(args.dataset)

    model_name = DEFAULT_MODEL

    total = len(questions)

    execution_successful = 0
    correct_results = 0
    corrected_queries = 0
    evaluation_records = []

    print(f"\nModel   : {model_name}")
    print(f"Dataset : {args.dataset}")
    print(f"Running evaluation on {total} questions...\n")

    for item in questions:
        question_id = item["id"]
        difficulty = item["difficulty"]
        question = item["question"]
        reference_sql = item["reference_sql"]

        print("=" * 70)
        print(f"Question {question_id} [{difficulty}]")
        print(question)

        try:
            # Run the real LLM Text-to-SQL pipeline.
            result = run_text_to_sql(question)

            execution_successful += 1

            if result["corrected"]:
                corrected_queries += 1

            generated_sql = result["sql"]
            generated_results = result["results"]

            print("\nGenerated SQL:")
            print(generated_sql)

            print("\nGenerated result:")
            print(generated_results)

            # Execute trusted reference SQL.
            reference_results = execute_query(reference_sql)

            is_correct = results_match(
                generated_results,
                reference_results,
            )

            evaluation_records.append(
                {
                    "id": question_id,
                    "difficulty": difficulty,
                    "question": question,
                    "generated_sql": generated_sql,
                    "generated_results": generated_results,
                    "corrected": result["corrected"],
                    "correction_attempts": result["correction_attempts"],
                }
            )

            if is_correct:
                correct_results += 1
                print("\nRESULT: CORRECT")
            else:
                print("\nRESULT: INCORRECT")

                print("\nExpected result:")
                print(reference_results)

                print("\nReference SQL:")
                print(reference_sql)

            if result["corrected"]:
                print(
                    f"\nCorrection attempts: "
                    f"{result['correction_attempts']}"
                )

        except Exception as error:
            print("\nEXECUTION: FAILED")
            print(f"Error: {error}")
            evaluation_records.append(
                {
                    "id": question_id,
                    "difficulty": difficulty,
                    "question": question,
                    "generated_sql": None,
                    "generated_results": None,
                    "correct": False,
                    "error": str(error),
                }
            )

        print()

    execution_rate = (
        (execution_successful / total) * 100
        if total
        else 0
    )

    result_accuracy = (
        (correct_results / total) * 100
        if total
        else 0
    )

    print("=" * 70)
    print("EVALUATION SUMMARY")
    print("=" * 70)

    print(f"Model                 : {model_name}")
    print(f"Dataset               : {args.dataset}")
    print(f"Total questions       : {total}")
    print(f"Executed successfully : {execution_successful}")
    print(f"Correct results       : {correct_results}")
    print(f"Corrected queries     : {corrected_queries}")

    print(f"\nExecution success rate: {execution_rate:.2f}%")
    print(f"Result accuracy       : {result_accuracy:.2f}%")

    results_dir = Path(__file__).parent / "results"
    results_dir.mkdir(exist_ok=True)

    dataset_name = Path(args.dataset).stem

    safe_model_name = (
        model_name
        .replace(":", "_")
        .replace("/", "_")
    )

    output_path = (
        results_dir
        / f"{dataset_name}__{safe_model_name}.json"
    )

    report = {
        "model": model_name,
        "dataset": args.dataset,
        "total_questions": total,
        "executed_successfully": execution_successful,
        "correct_results": correct_results,
        "corrected_queries": corrected_queries,
        "execution_success_rate": round(execution_rate, 2),
        "result_accuracy": round(result_accuracy, 2),
        "questions": evaluation_records,
    }

    with open(output_path, "w", encoding="utf-8") as file:
        json.dump(
            report,
            file,
            indent=2,
            default=str,
        )

    print(f"\nEvaluation report saved to:")
    print(output_path)


if __name__ == "__main__":
    main()